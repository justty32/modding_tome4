-- 歐拉麗三眷族的文獻。
--
-- lore 是開機一次性批次載入（原版在 mod/load.lua:111 對 /data/lore/lore.lua 做這件事），
-- addon 的 data/ 掛在私有的 /data-orario/ 不會被自動掃到，所以 hooks/load.lua 必須
-- 自己再 PartyLore:loadDefinition 一次（漏了 → 撿書時 learnLore 靜默無效）。
--
-- id 必須與各眷族據點 objects.lua 裡 lore 書物件的 lore 欄位完全一致。

newLore{
	id = "orario-fam-hearth",
	category = "orario familias",
	name = "爐灶之家的規矩",
	lore = [[赫斯緹雅眷族的會規只有三條：對同伴守信、對客人奉茶、對巴別塔保持敬畏。

我們沒有自己的高塔，沒有數十人的冒險者隊伍，連據點都是舊神祠改建的。
但歐拉麗就是這樣的地方：名聲再小的眷族，只要爐灶還點著火，就會有人上門求助，
也總有人願意分你一碗湯。

爐灶女神不獎賞強者，只獎賞守約的人。這條規矩，我們比誰都清楚。]],
}

