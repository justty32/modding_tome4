	name = "中層巡邏守則",
	lore = [[巴別塔不是只有怪物。

越往深處走，資源越稀有，也就越有人想用別人的命換自己的利益。洛基眷族之所以
接下中層巡邏的差事，不是因為我們最有耐心，而是因為我們最有把握：每一層誰在、
誰該走、誰該留下，我們都記錄在案。

守則第一條：巡邏時可以出手，不可以記仇。守則第二條：見死不救的隊員，
當天就除名。第三條只有一句話——「巴別塔吃人，但洛基不吃自己人」。]],
}

